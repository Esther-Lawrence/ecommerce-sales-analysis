-- Question 40: Which customer segment has the highest average spending?
WITH Customer_Spending AS (
    SELECT
        `Customer ID`,
        SUM(Revenue_Cleaned) AS Total_Spending
    FROM ecommerce_cleaned
    GROUP BY `Customer ID`
),
Customer_Segments AS (
    SELECT
        `Customer ID`,
        Total_Spending,
        CASE
            WHEN Total_Spending > 5000 THEN 'VIP'
            WHEN Total_Spending >= 2000 THEN 'Regular'
            ELSE 'Low-Value'
        END AS Customer_Segment
    FROM Customer_Spending
)
