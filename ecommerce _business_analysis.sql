WITH Daily_Revenue AS (
    SELECT
        DATE(`Order Date`) AS Sales_Date,
        SUM(Revenue_Cleaned) AS Daily_Revenue
    FROM ecommerce_cleaned
    GROUP BY DATE(`Order Date`)
)

SELECT
    Sales_Date,
    Daily_Revenue,
    SUM(Daily_Revenue) OVER (
        ORDER BY Sales_Date
        ROWS BETWEEN UNBOUNDED PRECEDING
        AND CURRENT ROW
    ) AS Running_Total
FROM Daily_Revenue
ORDER BY Sales_Date;

