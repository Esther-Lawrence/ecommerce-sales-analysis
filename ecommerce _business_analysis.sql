    Customer_Segment,
    COUNT(*) AS Total_Customers,
    ROUND(AVG(Total_Spending), 2) AS Average_Spending
FROM Customer_Segments
GROUP BY Customer_Segment
ORDER BY Average_Spending DESC;

-- Question 41: What is the average time between repeat purchases?
WITH Cleaned_Dates AS (
    SELECT
        `Customer ID`,
        `Order ID`,
        STR_TO_DATE(
            NULLIF(TRIM(`Order Date`), ''),
            '%c/%e/%Y'
        ) AS Purchase_Date
    FROM ecommerce_cleaned
),
Customer_Orders AS (
    SELECT
        `Customer ID`,
        `Order ID`,
        MIN(Purchase_Date) AS Purchase_Date
    FROM Cleaned_Dates
    WHERE Purchase_Date IS NOT NULL
    GROUP BY `Customer ID`, `Order ID`
),
Previous_Purchases AS (
    SELECT
        `Customer ID`,
        Purchase_Date,
        LAG(Purchase_Date) OVER (
            PARTITION BY `Customer ID`
            ORDER BY Purchase_Date
        ) AS Previous_Purchase_Date
    FROM Customer_Orders
)
SELECT
    ROUND(
        AVG(
            DATEDIFF(
                Purchase_Date,
                Previous_Purchase_Date
            )
        ),
        2
    ) AS Average_Days_Between_Purchases
FROM Previous_Purchases
WHERE Previous_Purchase_Date IS NOT NULL;

-- Question 42: Are sales increasing or decreasing over time?
WITH Cleaned_Dates AS (
    SELECT
        STR_TO_DATE(
            NULLIF(TRIM(`Order Date`), ''),
            '%c/%e/%Y'
        ) AS Sales_Date,
        Revenue_Cleaned
    FROM ecommerce_cleaned
),
Monthly_Revenue AS (
    SELECT
        DATE_FORMAT(Sales_Date, '%Y-%m') AS Sales_Month,
        SUM(Revenue_Cleaned) AS Total_Revenue
    FROM Cleaned_Dates
    WHERE Sales_Date IS NOT NULL
    GROUP BY DATE_FORMAT(Sales_Date, '%Y-%m')
),
Revenue_Trend AS (
    SELECT
        Sales_Month,
        Total_Revenue,
        LAG(Total_Revenue) OVER (
            ORDER BY Sales_Month
        ) AS Previous_Month_Revenue
    FROM Monthly_Revenue
)
SELECT
    Sales_Month,
    ROUND(Total_Revenue, 2) AS Total_Revenue,
    ROUND(Previous_Month_Revenue, 2) AS Previous_Month_Revenue,
    ROUND(
        (Total_Revenue - Previous_Month_Revenue) * 100.0 /
        NULLIF(Previous_Month_Revenue, 0),
        2
    ) AS Growth_Percentage,
    CASE
        WHEN Previous_Month_Revenue IS NULL
            THEN 'No Previous Month'
        WHEN Total_Revenue > Previous_Month_Revenue
            THEN 'Increasing'
        WHEN Total_Revenue < Previous_Month_Revenue
            THEN 'Decreasing'
        ELSE 'No Change'
    END AS Sales_Trend
FROM Revenue_Trend
ORDER BY Sales_Month;